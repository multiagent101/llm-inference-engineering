@dataclass
class RAGCostReport:
    """
    Full per-step cost and latency report for one RAG query.

    Attributes
    ----------
    query:
        The user question that was answered.
    model:
        Anthropic model used for the LLM call.
    chunks_retrieved:
        Number of chunks passed to the LLM as context.
    avg_similarity_score:
        Mean cosine similarity of the retrieved chunks to the query.
    top_similarity_score:
        Highest cosine similarity among retrieved chunks.

    Token counts
    ------------
    token_query:
        Tokens in the user query alone.
    token_system:
        Tokens in the system / template text.
    token_context:
        Tokens in the injected chunk context.
    token_input_total:
        Sum of all input tokens billed (system + query + context).
    token_response:
        Output tokens generated by the model.

    Latency (ms)
    ------------
    embedding_latency_ms:
        Time to encode the query with SentenceTransformer.
    retrieval_latency_ms:
        Time to compute cosine similarities over the chunk corpus.
    reranking_latency_ms:
        Time to sort and select the top-k chunks.
    context_injection_latency_ms:
        Time to assemble the final prompt string.
    llm_latency_ms:
        Wall-clock time for the Anthropic API call.
    total_latency_ms:
        End-to-end wall clock from query to response.

    Costs (USD)
    -----------
    cost_embedding_query_usd:
        Monetary cost of the embedding step ($0 for local model).
    cost_llm_input_usd:
        LLM cost for all input tokens.
    cost_llm_output_usd:
        LLM cost for output tokens.
    cost_llm_call_usd:
        Total LLM cost (input + output).
    cost_total_usd:
        Pipeline total (embedding + LLM).

    Breakdown
    ---------
    breakdown_pct:
        Fraction of ``cost_total_usd`` attributed to each token category:
        ``system``, ``query``, ``context``, ``response``, ``embedding``.

    response:
        The model's answer text.
    """

    query:                      str
    model:                      str
    chunks_retrieved:           int
    avg_similarity_score:       float
    top_similarity_score:       float

    # Tokens
    token_query:                int
    token_system:               int
    token_context:              int
    token_input_total:          int
    token_response:             int

    # Latency
    embedding_latency_ms:       float
    retrieval_latency_ms:       float
    reranking_latency_ms:       float
    context_injection_latency_ms: float
    llm_latency_ms:             float
    total_latency_ms:           float

    # Costs
    cost_embedding_query_usd:   float
    cost_llm_input_usd:         float
    cost_llm_output_usd:        float
    cost_llm_call_usd:          float
    cost_total_usd:             float

    # Breakdown
    breakdown_pct:              dict[str, float]

    response:                   str


@dataclass
class ChunkSizeAnalysis:
    """
    Cost and quality metrics for one chunk-size configuration.

    Attributes
    ----------
    chunk_size:
        Token window (in whitespace-split words) used for chunking.
    num_chunks:
        Total number of chunks the document was split into.
    top_k_retrieved:
        Number of chunks selected as context (capped at ``num_chunks``).
    avg_top_similarity:
        Mean cosine similarity of the top-k chunks to the query.
    context_tokens_est:
        Approximate token count of the assembled context (chars / 4).
    query_tokens_est:
        Approximate token count of the query.
    estimated_llm_input_tokens:
        Total estimated input tokens (system template + query + context).
    estimated_llm_cost_usd:
        Estimated LLM cost for one query using this chunk configuration.
    embedding_time_ms:
        Time to embed all chunks and the query.
    retrieval_time_ms:
        Time to rank chunks by similarity and select top-k.
    quality_cost_ratio:
        ``avg_top_similarity / estimated_llm_cost_usd`` — higher is better.
    """

    chunk_size:                 int
    num_chunks:                 int
    top_k_retrieved:            int
    avg_top_similarity:         float
    context_tokens_est:         int
    query_tokens_est:           int
    estimated_llm_input_tokens: int
    estimated_llm_cost_usd:     float
    embedding_time_ms:          float
    retrieval_time_ms:          float
    quality_cost_ratio:         float


@dataclass
class ChunkBenchmarkResult:
    """
    Cross-chunk-size benchmark outcome with an optimal-size recommendation.

    Attributes
    ----------
    query:
        The query used for all comparisons.
    model:
        Model whose pricing was used to estimate LLM costs.
    analyses:
        One :class:`ChunkSizeAnalysis` per tested chunk size, sorted by
        ``chunk_size`` ascending.
    optimal_chunk_size:
        Chunk size with the highest ``quality_cost_ratio``.
    baseline_cost_usd:
        Estimated LLM cost at the largest (most expensive) chunk size.
    optimal_cost_usd:
        Estimated LLM cost at the optimal chunk size.
    savings_vs_largest_pct:
        Percentage cost reduction vs. the largest chunk size.
    recommendation:
        Human-readable recommendation string.
    """

    query:                   str
    model:                   str
    analyses:                list[ChunkSizeAnalysis]
    optimal_chunk_size:      int
    baseline_cost_usd:       float
    optimal_cost_usd:        float
    savings_vs_largest_pct:  float
    recommendation:          str


