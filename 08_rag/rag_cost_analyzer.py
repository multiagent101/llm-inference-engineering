_SYSTEM_TEMPLATE = (
    "Answer the question using ONLY the provided context passages. "
    "If the answer cannot be found in the context, say so explicitly.\n\n"
    "Context:\n{context}"
)
# Fixed overhead from the system template excluding the context slot
_SYSTEM_OVERHEAD_CHARS = len(_SYSTEM_TEMPLATE.replace("{context}", ""))


class RAGCostAnalyzer:
    """
    Measures and reports the per-step cost of a RAG query pipeline.

    Parameters
    ----------
    embedding_model:
        HuggingFace sentence-transformers model name.  Downloaded on first
        use (~22 MB for ``all-MiniLM-L6-v2``).
    top_k:
        Number of chunks to retrieve and inject as context.
    max_tokens:
        Maximum tokens for the LLM response.
    api_key:
        Anthropic API key; falls back to ``ANTHROPIC_API_KEY`` env var.
    output_file:
        Path for persisting analyses.
    """

    def __init__(
        self,
        embedding_model: str           = "all-MiniLM-L6-v2",
        top_k:           int           = 3,
        max_tokens:      int           = 512,
        api_key:         Optional[str] = None,
        output_file:     Optional[Path] = None,
    ) -> None:
        print(f"  Loading embedding model '{embedding_model}' ...", end=" ", flush=True)
        self._embedder        = SentenceTransformer(embedding_model)
        self._embedding_model = embedding_model
        print("ready.")

        self._client     = anthropic.Anthropic(
            api_key=api_key or os.environ.get("ANTHROPIC_API_KEY", "")
        )
        self._top_k      = top_k
        self._max_tokens = max_tokens
        self._out_file   = output_file or _OUTPUT_FILE

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _split_into_chunks(text: str, chunk_size: int, overlap: int = 20) -> list[str]:
        """
        Split *text* into overlapping word-count windows.

        Parameters
        ----------
        text:
            Full document text.
        chunk_size:
            Target number of whitespace-delimited words per chunk.
        overlap:
            Number of words shared between consecutive chunks (sliding window).

        Returns
        -------
        list[str]
            Non-empty chunk strings.
        """
        words  = text.split()
        step   = max(1, chunk_size - overlap)
        chunks = []
        for start in range(0, len(words), step):
            chunk = " ".join(words[start : start + chunk_size])
            if chunk:
                chunks.append(chunk)
        return chunks

    def _embed(self, texts: list[str]) -> np.ndarray:
        """Return a (N, D) float32 embedding matrix for *texts*."""
        return self._embedder.encode(texts, convert_to_numpy=True, show_progress_bar=False)

    @staticmethod
    def _cos_sim(query_vec: np.ndarray, corpus_mat: np.ndarray) -> np.ndarray:
        """Return 1-D cosine similarity array (len = len(corpus))."""
        return cosine_similarity(query_vec.reshape(1, -1), corpus_mat)[0]

    @staticmethod
    def _approx_tokens(text: str) -> int:
        """Rough token estimate: 4 characters per token (used for benchmarks only)."""
        return max(1, len(text) // 4)

    def _build_prompt(self, query: str, chunks: list[str]) -> str:
        """Assemble the full user-facing message (context already injected)."""
        context = "\n\n---\n\n".join(
            f"[Chunk {i+1}]\n{chunk}" for i, chunk in enumerate(chunks)
        )
        system_body = _SYSTEM_TEMPLATE.format(context=context)
        # Return as the user message; system prompt is passed separately in the API call
        return system_body, query

    # ------------------------------------------------------------------
    # analyze
    # ------------------------------------------------------------------

    def analyze(
        self,
        query:            str,
        retrieved_chunks: list[str],
        model:            str = "claude-haiku-4-5",
    ) -> RAGCostReport:
        """
        Run a full RAG pipeline on *query* using *retrieved_chunks* as the
        corpus, measure every step, and return a :class:`RAGCostReport`.

        The method performs: embed query -> embed & rerank chunks -> inject
        context -> count tokens -> call LLM.

        Parameters
        ----------
        query:
            User question.
        retrieved_chunks:
            Candidate text passages (already retrieved from a vector store or
            passed directly).  The method re-embeds them for reranking.
        model:
            Anthropic model to call for the final answer.

        Returns
        -------
        RAGCostReport
            Fully populated cost and latency report.
        """
        t_pipeline_start = time.perf_counter()

        # ---- Step 1: Embed query ----------------------------------------
        t0 = time.perf_counter()
        query_vec = self._embed([query])[0]
        embedding_latency_ms = (time.perf_counter() - t0) * 1_000

        # ---- Step 2: Embed corpus (for reranking) -----------------------
        t0 = time.perf_counter()
        corpus_mat = self._embed(retrieved_chunks)
        sims       = self._cos_sim(query_vec, corpus_mat)
        retrieval_latency_ms = (time.perf_counter() - t0) * 1_000

        # ---- Step 3: Rerank — select top-k ------------------------------
        t0 = time.perf_counter()
        k          = min(self._top_k, len(retrieved_chunks))
        top_idx    = np.argsort(sims)[::-1][:k]
        top_chunks = [retrieved_chunks[i] for i in top_idx]
        top_sims   = sims[top_idx]
        reranking_latency_ms = (time.perf_counter() - t0) * 1_000

        # ---- Step 4: Context injection ----------------------------------
        t0 = time.perf_counter()
        system_text, user_text = self._build_prompt(query, top_chunks)
        context_injection_latency_ms = (time.perf_counter() - t0) * 1_000

        # ---- Step 5: Count tokens (accurate, no generation cost) --------
        token_count = self._client.messages.count_tokens(
            model    = model,
            system   = system_text,
            messages = [{"role": "user", "content": user_text}],
        )
        total_input_tokens = token_count.input_tokens

        # Approximate per-category token split for breakdown
        token_query_est   = self._approx_tokens(query)
        token_context_est = self._approx_tokens(
            "\n\n---\n\n".join(f"[Chunk {i+1}]\n{c}" for i, c in enumerate(top_chunks))
        )
        token_system_est  = max(0, total_input_tokens - token_query_est - token_context_est)

        # ---- Step 6: LLM call -------------------------------------------
        t0 = time.perf_counter()
        response_msg = self._client.messages.create(
            model      = model,
            max_tokens = self._max_tokens,
            system     = system_text,
            messages   = [{"role": "user", "content": user_text}],
        )
        llm_latency_ms = (time.perf_counter() - t0) * 1_000

        actual_input  = response_msg.usage.input_tokens
        actual_output = response_msg.usage.output_tokens
        response_text = response_msg.content[0].text if response_msg.content else ""

        total_latency_ms = (time.perf_counter() - t_pipeline_start) * 1_000

        # ---- Costs ------------------------------------------------------
        cost_embed   = 0.0   # local sentence-transformers
        cost_input   = _input_price(model)  * actual_input
        cost_output  = _output_price(model) * actual_output
        cost_llm     = cost_input + cost_output
        cost_total   = cost_embed + cost_llm

        # Per-category cost for breakdown (proportional split on input side)
        def _share(tok_est: int, total_est: int, total_cost: float) -> float:
            return (tok_est / total_est * total_cost) if total_est > 0 else 0.0

        total_est = token_query_est + token_context_est + token_system_est
        breakdown_pct: dict[str, float] = {
            "embedding_pct":  0.0,
            "system_pct":     round(_share(token_system_est,  total_est, cost_input) / cost_total * 100, 1) if cost_total else 0.0,
            "query_pct":      round(_share(token_query_est,   total_est, cost_input) / cost_total * 100, 1) if cost_total else 0.0,
            "context_pct":    round(_share(token_context_est, total_est, cost_input) / cost_total * 100, 1) if cost_total else 0.0,
            "response_pct":   round(cost_output / cost_total * 100, 1) if cost_total else 0.0,
        }

        report = RAGCostReport(
            query                        = query,
            model                        = model,
            chunks_retrieved             = k,
            avg_similarity_score         = float(np.mean(top_sims)),
            top_similarity_score         = float(top_sims[0]) if len(top_sims) else 0.0,
            token_query                  = token_query_est,
            token_system                 = token_system_est,
            token_context                = token_context_est,
            token_input_total            = actual_input,
            token_response               = actual_output,
            embedding_latency_ms         = round(embedding_latency_ms, 1),
            retrieval_latency_ms         = round(retrieval_latency_ms, 1),
            reranking_latency_ms         = round(reranking_latency_ms, 1),
            context_injection_latency_ms = round(context_injection_latency_ms, 1),
            llm_latency_ms               = round(llm_latency_ms, 1),
            total_latency_ms             = round(total_latency_ms, 1),
            cost_embedding_query_usd     = cost_embed,
            cost_llm_input_usd           = round(cost_input,  8),
            cost_llm_output_usd          = round(cost_output, 8),
            cost_llm_call_usd            = round(cost_llm,    8),
            cost_total_usd               = round(cost_total,  8),
            breakdown_pct                = breakdown_pct,
            response                     = response_text,
        )
        return report

    # ------------------------------------------------------------------
    # benchmark_chunk_sizes
    # ------------------------------------------------------------------

    def benchmark_chunk_sizes(
        self,
        query:       str,
        document:    str,
        chunk_sizes: list[int]    = None,
        top_k:       Optional[int] = None,
        model:       str           = "claude-haiku-4-5",
    ) -> ChunkBenchmarkResult:
        """
        Compare retrieval quality and estimated LLM cost across chunk sizes.

        No LLM calls are made; costs are estimated from token counts.
        Use this to choose a chunk size before paying for a live pipeline.

        Parameters
        ----------
        query:
            User question used to rank chunk relevance.
        document:
            Full document text to chunk.
        chunk_sizes:
            List of word-count window sizes to evaluate.
            Defaults to ``[128, 256, 512, 1024]``.
        top_k:
            Chunks to retrieve per configuration.  Defaults to
            ``self._top_k``.
        model:
            Model whose pricing is used for cost estimation.

        Returns
        -------
        ChunkBenchmarkResult
            Contains one :class:`ChunkSizeAnalysis` per chunk size plus
            the optimal recommendation.
        """
        if chunk_sizes is None:
            chunk_sizes = [128, 256, 512, 1024]
        k = top_k if top_k is not None else self._top_k

        # System template overhead token estimate (fixed across chunk sizes)
        system_overhead_tokens = self._approx_tokens(
            _SYSTEM_TEMPLATE.replace("{context}", "")
        )
        query_tokens_est = self._approx_tokens(query)

        # Embed the query once
        t0        = time.perf_counter()
        query_vec = self._embed([query])[0]
        _query_embed_ms = (time.perf_counter() - t0) * 1_000

        analyses: list[ChunkSizeAnalysis] = []

        for cs in sorted(chunk_sizes):
            chunks = self._split_into_chunks(document, cs)
            if not chunks:
                continue

            # Embed corpus
            t0           = time.perf_counter()
            corpus_mat   = self._embed(chunks)
            embed_ms     = (time.perf_counter() - t0) * 1_000 + _query_embed_ms

            # Retrieve top-k
            t0           = time.perf_counter()
            sims         = self._cos_sim(query_vec, corpus_mat)
            actual_k     = min(k, len(chunks))
            top_idx      = np.argsort(sims)[::-1][:actual_k]
            top_chunks   = [chunks[i] for i in top_idx]
            top_sims     = sims[top_idx]
            retrieval_ms = (time.perf_counter() - t0) * 1_000

            context_text       = "\n\n---\n\n".join(
                f"[Chunk {i+1}]\n{c}" for i, c in enumerate(top_chunks)
            )
            context_tokens_est = self._approx_tokens(context_text)
            total_input_est    = system_overhead_tokens + query_tokens_est + context_tokens_est

            # Output token estimate: assume ~200 tokens average response
            output_tokens_est  = 200
            est_cost = _llm_cost(model, total_input_est, output_tokens_est)

            qcr = float(np.mean(top_sims)) / est_cost if est_cost > 0 else 0.0

            analyses.append(ChunkSizeAnalysis(
                chunk_size                 = cs,
                num_chunks                 = len(chunks),
                top_k_retrieved            = actual_k,
                avg_top_similarity         = round(float(np.mean(top_sims)), 4),
                context_tokens_est         = context_tokens_est,
                query_tokens_est           = query_tokens_est,
                estimated_llm_input_tokens = total_input_est,
                estimated_llm_cost_usd     = round(est_cost, 8),
                embedding_time_ms          = round(embed_ms, 1),
                retrieval_time_ms          = round(retrieval_ms, 1),
                quality_cost_ratio         = round(qcr, 2),
            ))

        if not analyses:
            raise ValueError("No valid analyses produced — check document and chunk_sizes.")

        # Optimal = best quality/cost ratio
        optimal     = max(analyses, key=lambda a: a.quality_cost_ratio)
        baseline    = max(analyses, key=lambda a: a.chunk_size)
        savings_pct = (
            (baseline.estimated_llm_cost_usd - optimal.estimated_llm_cost_usd)
            / baseline.estimated_llm_cost_usd * 100
            if baseline.estimated_llm_cost_usd > 0 else 0.0
        )

        recommendation = (
            f"Optimal chunk size for this document is {optimal.chunk_size} words "
            f"(quality/cost ratio {optimal.quality_cost_ratio:.2f}). "
            f"Estimated saving: {savings_pct:.1f}% vs the largest chunk size "
            f"({baseline.chunk_size} words)."
        )

        return ChunkBenchmarkResult(
            query                  = query,
            model                  = model,
            analyses               = analyses,
            optimal_chunk_size     = optimal.chunk_size,
            baseline_cost_usd      = baseline.estimated_llm_cost_usd,
            optimal_cost_usd       = optimal.estimated_llm_cost_usd,
            savings_vs_largest_pct = round(savings_pct, 1),
            recommendation         = recommendation,
        )

    # ------------------------------------------------------------------
    # save_analysis
    # ------------------------------------------------------------------

    def save_analysis(
        self,
        report:    Optional[RAGCostReport]      = None,
        benchmark: Optional[ChunkBenchmarkResult] = None,
    ) -> Path:
        """
        Persist *report* and/or *benchmark* to ``rag_cost_analysis.json``.

        Overwrites the previous file.  Pass either or both arguments.

        Parameters
        ----------
        report:
            :class:`RAGCostReport` from :meth:`analyze`, or ``None``.
        benchmark:
            :class:`ChunkBenchmarkResult` from :meth:`benchmark_chunk_sizes`,
            or ``None``.

        Returns
        -------
        Path
            Absolute path of the written file.
        """
        payload: dict = {
            "saved_at": datetime.now(timezone.utc).isoformat(),
        }
        if benchmark is not None:
            payload["benchmark"] = asdict(benchmark)
        if report is not None:
            payload["analysis"] = asdict(report)

        self._out_file.write_text(
            json.dumps(payload, indent=2, default=str),
            encoding="utf-8",
        )
        return self._out_file


