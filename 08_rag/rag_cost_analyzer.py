"""
rag_cost_analyzer.py - Per-step cost and latency analysis for a RAG pipeline.

Measures every stage of retrieval-augmented generation:
  1. Embedding    — query encoding with a local SentenceTransformer (free).
  2. Retrieval    — cosine-similarity search over pre-embedded corpus chunks.
  3. Reranking    — re-scoring the retrieved set and selecting the top-k.
  4. Context injection — assembling the final prompt string.
  5. LLM call    — actual Anthropic Messages API call; billed by token.

Cost model
----------
Sentence-transformers runs locally; its monetary cost is zero, though its
latency is measured.  All monetary cost comes from the LLM call.  The
breakdown_pct field shows what fraction of the LLM bill comes from each
token category (system prompt, query, context, response).

Chunk-size benchmark
--------------------
``benchmark_chunk_sizes`` splits a document into windows of different sizes,
embeds everything locally, retrieves the top-k chunks per size, and estimates
the LLM cost from token counts — without actually calling the LLM.  It then
recommends the chunk size that maximises retrieval quality per dollar spent.
"""

from __future__ import annotations

import json
import os
import time
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

import anthropic
import numpy as np
from dotenv import load_dotenv
from sentence_transformers import SentenceTransformer
from sklearn.metrics.pairwise import cosine_similarity

load_dotenv(Path(__file__).parent.parent / ".env")

_OUTPUT_FILE = Path(__file__).parent / "rag_cost_analysis.json"

# ---------------------------------------------------------------------------
# Pricing (USD per token) — standard (non-batch) rates
# ---------------------------------------------------------------------------

_MODEL_PRICING: dict[str, dict[str, float]] = {
    "claude-haiku-4-5":          {"input": 0.80 / 1_000_000, "output":  4.00 / 1_000_000},
    "claude-haiku-4-5-20251001": {"input": 0.80 / 1_000_000, "output":  4.00 / 1_000_000},
    "claude-sonnet-4-5":         {"input": 3.00 / 1_000_000, "output": 15.00 / 1_000_000},
    "claude-sonnet-4-6":         {"input": 3.00 / 1_000_000, "output": 15.00 / 1_000_000},
    "claude-opus-4-7":           {"input": 5.00 / 1_000_000, "output": 25.00 / 1_000_000},
}
_DEFAULT_INPUT_PRICE:  float = 3.00 / 1_000_000
_DEFAULT_OUTPUT_PRICE: float = 15.00 / 1_000_000


def _input_price(model: str) -> float:
    return _MODEL_PRICING.get(model, {"input": _DEFAULT_INPUT_PRICE})["input"]


def _output_price(model: str) -> float:
    return _MODEL_PRICING.get(model, {"output": _DEFAULT_OUTPUT_PRICE})["output"]


def _llm_cost(model: str, input_tokens: int, output_tokens: int) -> float:
    return _input_price(model) * input_tokens + _output_price(model) * output_tokens


